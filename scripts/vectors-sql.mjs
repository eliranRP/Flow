/**
 * FLOW-1305: writes supabase/tests/database/vectors_<builder>.test.sql, one pgTAP file per builder
 * whose SQL core exists, from the shared vectors in packages/shared/fixtures/vectors/<builder>/.
 * A core "exists" when a migration creates `function private.<core>`. None does yet, so a run
 * writes nothing today.
 *
 *   node scripts/vectors-sql.mjs           write the files
 *   node scripts/vectors-sql.mjs --check   exit 1 when a file is missing, stale, or left for a core that is gone
 *
 * `--root <dir>` reads another tree (the test uses it).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** builder directory name -> the SQL core that takes the vector's input as jsonb and returns its expected as jsonb. */
export const BUILDERS = {
  "month-forecast": "month_forecast_build",
  "loan-schedule": "loan_schedule",
};

export const vectorsDir = "packages/shared/fixtures/vectors";
export const testsDir = "supabase/tests/database";
export const migrationsDir = "supabase/migrations";

/** @param {string} builder */
export const sqlPathFor = (builder) => `${testsDir}/vectors_${builder.replaceAll("-", "_")}.test.sql`;

/**
 * @param {string} root
 * @param {string} core
 */
export function coreExists(root, core) {
  const dir = path.join(root, migrationsDir);
  if (!existsSync(dir)) return false;
  const create = new RegExp(`create\\s+(or\\s+replace\\s+)?function\\s+private\\.${core}\\s*\\(`, "i");
  return readdirSync(dir)
    .filter((file) => file.endsWith(".sql"))
    .some((file) => create.test(readFileSync(path.join(dir, file), "utf8")));
}

/**
 * @param {string} root
 * @param {string} builder
 * @returns {{ name: string, input: unknown, expected: unknown }[]}
 */
export function readVectors(root, builder) {
  const dir = path.join(root, vectorsDir, builder);
  return readdirSync(dir)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => {
      const vector = JSON.parse(readFileSync(path.join(dir, file), "utf8"));
      if (vector.name !== file.slice(0, -".json".length)) {
        throw new Error(`${builder}/${file}: name "${vector.name}" does not match the file`);
      }
      return vector;
    });
}

/** A dollar-quoted literal whose tag does not occur in the text. */
function quote(text) {
  let tag = "v";
  while (text.includes(`$${tag}$`)) tag += "v";
  return `$${tag}$${text}$${tag}$`;
}

/**
 * @param {string} builder
 * @param {string} core
 * @param {{ name: string, input: unknown, expected: unknown }[]} vectors
 */
export function renderSql(builder, core, vectors) {
  const lines = [
    `-- GENERATED by scripts/vectors-sql.mjs from ${vectorsDir}/${builder}/*.json. Do not edit; run the script.`,
    `-- FLOW-1305: each vector's input goes to private.${core} and must give the vector's expected answer.`,
    "",
    "begin;",
    "",
    `select plan(${String(vectors.length)});`,
    "",
  ];
  for (const vector of vectors) {
    const input = quote(JSON.stringify(vector.input));
    const expected = quote(JSON.stringify(vector.expected));
    lines.push(`select is(private.${core}(${input}::jsonb), ${expected}::jsonb, ${quote(vector.name)});`);
  }
  lines.push("", "select * from finish();", "rollback;", "");
  return lines.join("\n");
}

/**
 * @param {string} root
 * @param {{ check?: boolean }} [options]
 * @returns {{ written: string[], problems: string[] }}
 */
export function run(root, { check = false } = {}) {
  const written = [];
  const problems = [];
  for (const [builder, core] of Object.entries(BUILDERS)) {
    const file = sqlPathFor(builder);
    const full = path.join(root, file);
    const has = existsSync(full);
    if (!coreExists(root, core)) {
      if (has && check) problems.push(`${file}: no migration creates private.${core}; delete the file.`);
      if (has && !check) {
        rmSync(full);
        written.push(`${file} (removed)`);
      }
      continue;
    }
    const sql = renderSql(builder, core, readVectors(root, builder));
    if (has && readFileSync(full, "utf8") === sql) continue;
    if (check) {
      problems.push(`${file}: ${has ? "is stale" : "is missing"}; run node scripts/vectors-sql.mjs and commit it.`);
    } else {
      mkdirSync(path.dirname(full), { recursive: true });
      writeFileSync(full, sql);
      written.push(file);
    }
  }
  return { written, problems };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf("--root");
  const root = path.resolve(at > 0 ? (process.argv[at + 1] ?? ".") : path.join(path.dirname(fileURLToPath(import.meta.url)), ".."));
  const check = process.argv.includes("--check");
  const { written, problems } = run(root, { check });
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
  if (check) console.log("vectors-sql: every generated vectors test file is up to date");
  else console.log(written.length === 0 ? "vectors-sql: nothing to write (no SQL core exists yet)" : `vectors-sql: wrote ${written.join(", ")}`);
}
