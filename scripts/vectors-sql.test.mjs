import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import { BUILDERS, coreExists, renderSql, run, sqlPathFor } from "./vectors-sql.mjs";

const repo = new URL("..", import.meta.url).pathname;
const script = new URL("./vectors-sql.mjs", import.meta.url).pathname;
const coreMigration = "supabase/migrations/20270101000000_core.sql";

/** A repo-shaped temp dir with one vector per builder and, optionally, a migration that creates the month core. */
function fixture({ core = false } = {}) {
  const root = mkdtempSync(path.join(tmpdir(), "vectors-sql-"));
  for (const builder of Object.keys(BUILDERS)) {
    const dir = path.join(root, "packages/shared/fixtures/vectors", builder);
    mkdirSync(dir, { recursive: true });
    const name = "first-vector";
    writeFileSync(path.join(dir, `${name}.json`), JSON.stringify({ name, input: { a: 1, text: "it's $v$ odd" }, expected: { total: 2 } }));
  }
  mkdirSync(path.join(root, "supabase/migrations"), { recursive: true });
  if (core) {
    writeFileSync(path.join(root, coreMigration), "create or replace function public.month_forecast_core(p jsonb) returns jsonb language sql as $$ select p $$;\n");
  }
  return root;
}

const cli = (root, ...args) => spawnSync("node", [script, "--root", root, ...args], { encoding: "utf8" });

test("the repo's vectors are readable and no SQL core exists yet, so nothing is generated", () => {
  const { written, problems } = run(repo, { check: true });
  assert.deepEqual(problems, []);
  assert.deepEqual(written, []);
  for (const builder of Object.keys(BUILDERS)) assert.equal(existsSync(path.join(repo, sqlPathFor(builder))), false);
  assert.equal(spawnSync("node", [script, "--check"], { encoding: "utf8" }).status, 0);
});

test("a builder without a core writes nothing, and --check passes", () => {
  const root = fixture();
  try {
    assert.deepEqual(run(root), { written: [], problems: [] });
    assert.deepEqual(run(root, { check: true }), { written: [], problems: [] });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("a builder whose core exists gets a pgTAP file, and only that builder", () => {
  const root = fixture({ core: true });
  try {
    assert.equal(coreExists(root, "month_forecast_core"), true);
    assert.equal(coreExists(root, "loan_schedule_core"), false);
    const { written } = run(root);
    assert.deepEqual(written, [sqlPathFor("month-forecast")]);
    assert.equal(existsSync(path.join(root, sqlPathFor("loan-schedule"))), false);
    const sql = readFileSync(path.join(root, sqlPathFor("month-forecast")), "utf8");
    assert.match(sql, /GENERATED by scripts\/vectors-sql\.mjs/);
    assert.match(sql, /select plan\(1\);/);
    assert.match(sql, /select is\(public\.month_forecast_core\(\$vv\$/);
    // The vector's own text holds $v$, so the quote tag grows instead of ending early.
    assert.match(sql, /\$vv\$\{"a":1,"text":"it's \$v\$ odd"\}\$vv\$::jsonb/);
    assert.deepEqual(run(root, { check: true }), { written: [], problems: [] });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("--check fails on a missing file, a stale file, an edited file, and a file left for a core that is gone", () => {
  const root = fixture({ core: true });
  const file = path.join(root, sqlPathFor("month-forecast"));
  const vector = path.join(root, "packages/shared/fixtures/vectors/month-forecast/first-vector.json");
  try {
    let result = cli(root, "--check");
    assert.equal(result.status, 1);
    assert.match(result.stderr, /is missing/);

    assert.equal(cli(root).status, 0);
    result = cli(root, "--check");
    assert.equal(result.status, 0, result.stderr);

    // A vector changes: the file on disk is now stale.
    writeFileSync(vector, JSON.stringify({ name: "first-vector", input: { a: 1 }, expected: { total: 3 } }));
    result = cli(root, "--check");
    assert.equal(result.status, 1);
    assert.match(result.stderr, /vectors_month_forecast\.test\.sql: is stale/);

    // The generated file is edited by hand: stale too, and a run puts it back.
    assert.equal(cli(root).status, 0);
    writeFileSync(file, `${readFileSync(file, "utf8")}-- edited\n`);
    assert.equal(cli(root, "--check").status, 1);
    assert.equal(cli(root).status, 0);
    assert.equal(cli(root, "--check").status, 0);

    // The core goes away: the file is left over.
    rmSync(path.join(root, coreMigration));
    result = cli(root, "--check");
    assert.equal(result.status, 1);
    assert.match(result.stderr, /no migration creates public\.month_forecast_core/);
    assert.equal(cli(root).status, 0);
    assert.equal(existsSync(file), false);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("a vector whose name does not match its file is refused", () => {
  const root = fixture({ core: true });
  try {
    writeFileSync(path.join(root, "packages/shared/fixtures/vectors/month-forecast/first-vector.json"), JSON.stringify({ name: "other", input: {}, expected: {} }));
    assert.throws(() => run(root), /does not match the file/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("renderSql numbers the plan and closes the transaction", () => {
  const sql = renderSql("loan-schedule", "loan_schedule_core", [
    { name: "a", input: { x: 1 }, expected: { y: 2 } },
    { name: "b", input: { x: 3 }, expected: { error: "rate" } },
  ]);
  assert.match(sql, /select plan\(2\);/);
  assert.equal(sql.match(/select is\(/g)?.length, 2);
  assert.match(sql, /select \* from finish\(\);\nrollback;\n$/);
});
