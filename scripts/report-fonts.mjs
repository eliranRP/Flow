#!/usr/bin/env node
/**
 * FLOW-162: writes supabase/functions/_shared/report_fonts.ts, the Rubik subsets the report PDF embeds
 * (Hebrew and Latin, 400 and 600), from @fontsource/rubik (SIL Open Font License 1.1). The edge function
 * bundles this module, so the PDF needs no file read at run time. Run it again after a font update.
 *
 * Usage: node scripts/report-fonts.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "app", "package.json"));
const files = path.join(path.dirname(require.resolve("@fontsource/rubik/package.json")), "files");
const out = path.join(root, "supabase/functions/_shared/report_fonts.ts");

const fonts = [
  ["HEBREW_400", "rubik-hebrew-400-normal.woff"],
  ["HEBREW_600", "rubik-hebrew-600-normal.woff"],
  ["LATIN_400", "rubik-latin-400-normal.woff"],
  ["LATIN_600", "rubik-latin-600-normal.woff"],
];

const lines = [
  "// Generated by scripts/report-fonts.mjs from @fontsource/rubik. Do not edit by hand.",
  "// Rubik: Copyright 2015 The Rubik Project Authors (https://github.com/googlefonts/rubik),",
  "// licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).",
  "",
];
for (const [name, file] of fonts) {
  lines.push(`export const ${name} = "${readFileSync(path.join(files, file)).toString("base64")}";`);
}
const text = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("report_fonts.ts is out of date: run node scripts/report-fonts.mjs");
    process.exit(1);
  }
  console.log("report_fonts.ts is up to date.");
} else {
  writeFileSync(out, text);
  console.log(`Wrote ${path.relative(root, out)}.`);
}
